export function resolveLocale(value: string | null | undefined): AppLocale | null {
  if (!value) return null;
  const normalized = value.trim().toLowerCase();
  if (normalized === "zh-tw" || normalized === "zh" || normalized.startsWith("zh-")) return "zh-TW";
  if (normalized === "en" || normalized.startsWith("en-")) return "en";
  if (normalized === "id" || normalized.startsWith("id-") || normalized === "in") return "id";
  return null;
}

export function intlLocale(locale: AppLocale) {
  return { "zh-TW": "zh-TW", en: "en-US", id: "id-ID" }[locale];
}

export function translate(
  locale: AppLocale,
  key: TranslationKey,
  values: Record<string, string | number> = {},
) {
  return dictionaries[locale][key].replace(/\{(\w+)\}/g, (match, name: string) => (
    values[name] === undefined ? match : String(values[name])
  ));
}

export function translateServerError(
  locale: AppLocale,
  message: string | null | undefined,
  fallbackKey: TranslationKey,
) {
  if (!message) return translate(locale, fallbackKey);
  if (locale === "zh-TW") return message;
  const key = serverErrorKeys[message];
  return translate(locale, key ?? fallbackKey);
}

export function statusTranslationKey(value: string): TranslationKey {
  const key = `status.${value}` as TranslationKey;
  return key in zhTW ? key : "status.closed";
}
